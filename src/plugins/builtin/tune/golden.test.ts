const SR = 48000;
const FRAMES = GOLDEN_FRAMES;
const SAMPLE_TOLERANCE = 0.002;
const DB_TOLERANCE = 0.1;
/** The params the CPU benchmark sweeps for this effect (its first automatable floats). */
const SWEPT = ['speed', 'mix'] as const;

interface Snapshot {
  /** Left channel every 256 frames. */
  left: number[];
  /** RMS of each 1024-frame chunk, per channel. */
  rmsL: number[];
  rmsR: number[];
}

/** [seconds from, MIDI note] of the melody; a null note is a rest. Notes glide over 30 ms. */
const NOTES: readonly [number, number | null][] = [
  [0, 57],
  [0.3, 61],
  [0.6, 64],
  [0.9, 66],
  [1.2, null],
  [1.3, 62],
  [1.65, 58],
];

/** A monophonic, voice-like melody: a harmonic series whose pitch glides between the notes, with vibrato. */
function melody(): Float32Array {
  const out = new Float32Array(FRAMES);
  let phase = 0;
  let current = 57;
  let target: number | null = 57;
  let segment = 0;
  let level = 0;
  for (let i = 0; i < FRAMES; i++) {
    const t = i / SR;
    while (segment + 1 < NOTES.length && t >= (NOTES[segment + 1] as [number, number | null])[0]) {
      segment++;
      target = (NOTES[segment] as [number, number | null])[1];
    }
    if (target !== null) current += (target - current) * (1 - Math.exp(-(1 / SR) / 0.03));
    level += ((target === null ? 0 : 0.25) - level) * (1 - Math.exp(-(1 / SR) / 0.01));
    const vibrato = t >= 1.65 ? 0.4 * Math.sin(2 * Math.PI * 5.5 * t) : 0;
    const f = 440 * Math.pow(2, (current + vibrato - 69) / 12);
    phase += f / SR;
    phase -= Math.floor(phase);
    let x = 0;
    for (let k = 1; k <= 12; k++) x += Math.sin(2 * Math.PI * k * phase) / k;
    out[i] = level * 0.6 * x;
  }
  return out;
}

const MELODY = melody();
const sweeps = goldenSweeps(tuneParams, SWEPT);

/** Renders `values` (a preset, or {} for the default patch) on the melody. */
function render(values: Record<string, ParamValue>): [Float32Array, Float32Array] {
  const params: Record<string, ParamValue | ((frame: number) => number)> = { ...values };
  for (const key of SWEPT) params[key] = sweeps[key] as (frame: number) => number;
  return runEffect(TuneKernel, tuneParams, (frame) => MELODY[frame] as number, FRAMES, { params });
}

function snapshot(values: Record<string, ParamValue>): Snapshot {
  const [L, R] = render(values);
  return {
    left: strided(L, 256).map((x) => Number(x.toFixed(7))),
    rmsL: chunkRms(L).map((x) => Number(x.toPrecision(6))),
    rmsR: chunkRms(R).map((x) => Number(x.toPrecision(6))),
  };
}

