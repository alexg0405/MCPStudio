/**
 * Golden output of the Vocoder kernel: the default patch and every preset, with a voice-like
 * sidechain (a moving pitch, syllables, a sibilant burst) on a music-like carrier, and the width,
 * formant and attack params swept by the CPU benchmark's automation in the whole run.
 *
 * The stored values are taken from the kernel before its band loop was restructured: every 256th
 * left-channel sample, and the RMS of each 1024-frame chunk of both channels. The tolerances are
 * 0.002 on the samples and 0.1 dB on the chunk RMS. To regenerate, run
 * `VOCODER_GOLDEN_RECORD=1 npx vitest run src/plugins/builtin/vocoder/golden.test.ts`: the test
 * prints the snapshots as one `GOLDEN_JSON` line, to paste between the GOLDEN markers.
 */
