  describe('Vocoder kernel golden output', () => {
    it.each(scenarios)('%s matches the stored output', (name, values) => {
      const want = GOLDEN[name];
      expect(want, `no golden snapshot for ${name}`).toBeDefined();
      const got = snapshot(values);
      expect(Math.max(...got.rmsL), 'scenario is silent').toBeGreaterThan(0.01);
      expect(got.left.length).toBe(want!.left.length);
      expect(got.rmsL.length).toBe(want!.rmsL.length);
      let maxSample = 0;
      got.left.forEach((x, i) => (maxSample = Math.max(maxSample, Math.abs(x - want!.left[i]!))));
      expect(maxSample, 'max sample difference').toBeLessThan(SAMPLE_TOLERANCE);
      let maxDb = 0;
      got.rmsL.forEach((x, i) => (maxDb = Math.max(maxDb, Math.abs(rmsDb(x, want!.rmsL[i]!)))));
      got.rmsR.forEach((x, i) => (maxDb = Math.max(maxDb, Math.abs(rmsDb(x, want!.rmsR[i]!)))));
      expect(maxDb, 'chunk RMS difference, dB').toBeLessThanOrEqual(DB_TOLERANCE);
    });
  });
