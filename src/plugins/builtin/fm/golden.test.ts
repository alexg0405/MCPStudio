/**
 * Golden output of the FM kernel: every preset and the default patch, played with a chord, a
 * velocity change, a pitch bend, the mod wheel and per-frame automation of several params (cutoff,
 * resonance, feedback, operator 2 level, operator 3 fine, vibrato depth) in the middle of the notes.
 *
 * The stored values are taken from the kernel before its param handling was optimised: every
 * 256th left-channel sample and the RMS of each channel, to within 1e-6. To regenerate, run
 * `FM_GOLDEN_RECORD=1 npx vitest run src/plugins/builtin/fm/golden.test.ts`: the test then fails
 * with the snapshots as JSON in its message (after `GOLDEN_JSON `) instead of comparing; paste
 * them into GOLDEN.
 */
