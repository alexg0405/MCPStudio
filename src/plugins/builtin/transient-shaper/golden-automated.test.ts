/** Steady output (constant params, same input) hashed bit for bit, from the kernel before the change. */
const STEADY = [
  { label: 'default settings', values: {}, hash: '54bfd610', hashRight: 'ae332172' },
  {
    label: 'non-default settings',
    values: { attack: 0.5, sustain: -0.4, length: 50, output: -3, mix: 0.7 },
    hash: '1f1e180f',
    hashRight: 'd81e9688',
  },
];

const renderSwept = () =>
  runEffect(TransientKernel, transientParams, goldenInput, GOLDEN_FRAMES, {
    params: goldenSweeps(transientParams, SWEPT),
  });

describe('TransientKernel with automated params', () => {
  it('keeps every chunk RMS within 0.1 dB of the reference', () => {
    const [left] = renderSwept();
    const rms = chunkRms(left);
    expect(rms.length).toBe(REF_RMS.length);
    const worst = Math.max(...rms.map((v, c) => Math.abs(rmsDb(v, REF_RMS[c] as number))));
    expect(worst).toBeLessThan(0.1);
  });

  it('keeps every 256th sample within 0.002 of the reference', () => {
    const [left] = renderSwept();
    expect(maxAbsDiff(strided(left), REF_SAMPLES)).toBeLessThan(0.002);
  });
});

describe('TransientKernel with steady params', () => {
  it.each(STEADY)('is bit-identical to the reference ($label)', ({ values, hash, hashRight }) => {
    const [left, right] = runEffect(TransientKernel, transientParams, goldenInput, GOLDEN_FRAMES, { params: values });
    expect(bitHash(left)).toBe(hash);
    expect(bitHash(right)).toBe(hashRight);
  });
});
