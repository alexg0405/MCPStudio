const SR = 48000;
const BLOCK = 128;
const BLOCKS = 560;
const FRAMES = BLOCKS * BLOCK;
const STRIDE = 256;
const TOLERANCE = 1e-6;

interface Snapshot {
  /** Left channel every STRIDE frames. */
  left: number[];
  rmsL: number;
  rmsR: number;
}

/** The frame of the block that contains `sec` (events happen at block starts). */
const blockFrame = (sec: number) => Math.round((sec * SR) / BLOCK) * BLOCK;

const rms = (x: Float32Array) => {
  let s = 0;
  for (let i = 0; i < x.length; i++) s += (x[i] as number) * (x[i] as number);
  return Math.sqrt(s / x.length);
};

const perFrame = (b0: number, fn: (t: number) => number) =>
  Float32Array.from({ length: BLOCK }, (_, i) => fn((b0 + i) / SR));

const clamp01 = (x: number) => (x < 0 ? 0 : x > 1 ? 1 : x);

/** Renders `values` (a preset, or {} for the default patch) through the scripted performance. */
function render(values: Record<string, ParamValue>): { L: Float32Array; R: Float32Array } {
  const k = new FmKernel(testHost(SR));
  const base = paramBlock(fmParams, values) as ParamBlock;
  const L = new Float32Array(FRAMES);
  const R = new Float32Array(FRAMES);
  const zero = new Float32Array([0]);
  const chord = [48, 55, 60, 64];
  const events: [number, () => void][] = [
    ...chord.map((key, n): [number, () => void] => [0, () => k.noteOn(key, 0.8, n + 1, 0, 0)]),
    [blockFrame(0.3), () => k.noteOn(67, 0.3, 10, 0, 0)],
    [blockFrame(0.45), () => k.noteOn(72, 1, 11, 0, 0)],
    [blockFrame(0.7), () => k.controlChange(1, 0.6)],
    [blockFrame(0.95), () => chord.forEach((key, n) => k.noteOff(n + 1, key, 0.5))],
    [blockFrame(1.1), () => k.controlChange(1, 0.1)],
    [blockFrame(1.2), () => k.noteOn(79, 0.6, 12, -0.5, 0.2)],
  ];
  for (let b0 = 0; b0 < FRAMES; b0 += BLOCK) {
    for (const [frame, run] of events) if (frame === b0) run();
    const t = b0 / SR;
    // Pitch bend: up 150 cents over 0.5–1.1 s, then back to centre.
    k.pitch = t >= 0.5 && t < 1.1 ? perFrame(b0, (x) => 150 * clamp01((x - 0.5) / 0.6)) : zero;
    const p = { ...base } as Record<string, Float32Array>;
    // Automation in the middle of the notes (0.6–0.9 s).
    if (t >= 0.6 && t < 0.9) {
      p.cutoff = perFrame(b0, (x) => 20000 * Math.pow(800 / 20000, (x - 0.6) / 0.3));
      p.resonance = perFrame(b0, (x) => 0.5 * clamp01((x - 0.6) / 0.3));
      p[opParam(2).level] = perFrame(b0, (x) => 0.45 + 0.4 * Math.sin(2 * Math.PI * 3 * x));
      p[opParam(3).fine] = perFrame(b0, (x) => 0.5 + 0.5 * Math.sin(2 * Math.PI * 1.7 * x));
    }
    if (t >= 0.75 && t < 1.0) {
      p.feedback = perFrame(b0, (x) => 0.2 + 0.6 * clamp01((x - 0.75) / 0.25));
      p.vibratoDepth = perFrame(b0, (x) => 40 * clamp01((x - 0.75) / 0.1));
    }
    const out = [L.subarray(b0, b0 + BLOCK), R.subarray(b0, b0 + BLOCK)];
    k.render(out, 0, BLOCK, p as unknown as ParamBlock);
  }
  return { L, R };
}

function snapshot(values: Record<string, ParamValue>): Snapshot {
  const { L, R } = render(values);
  const left: number[] = [];
  for (let i = 0; i < FRAMES; i += STRIDE) left.push(Number((L[i] as number).toFixed(8)));
  return { left, rmsL: Number(rms(L).toFixed(8)), rmsR: Number(rms(R).toFixed(8)) };
}

