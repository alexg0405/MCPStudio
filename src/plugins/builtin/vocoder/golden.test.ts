/** The params the CPU benchmark sweeps for this effect (its first automatable floats). */
const SWEPT = ['width', 'formant', 'attack'] as const;

interface Snapshot {
  /** Left channel every 256 frames. */
  left: number[];
  /** RMS of each 1024-frame chunk, per channel. */
  rmsL: number[];
  rmsR: number[];
}

/**
 * The modulator: a voice-like signal. A harmonic series on a pitch that moves around 140–170 Hz,
 * with formant peaks near 500 and 1500 Hz, a syllable pulse at 3.5 Hz, a sibilant noise burst and
 * silence at the end.
 */
function voice(): Float32Array {
  const out = new Float32Array(FRAMES);
  let phase = 0;
  let noise = 12345;
  for (let i = 0; i < FRAMES; i++) {
    const t = i / SR;
    const f0 = 155 + 15 * Math.sin(2 * Math.PI * 0.9 * t);
    phase += f0 / SR;
    phase -= Math.floor(phase);
    let x = 0;
    for (let k = 1; k <= 24; k++) {
      const f = k * f0;
      const formant = Math.exp(-(((f - 500) / 400) ** 2)) + 0.6 * Math.exp(-(((f - 1500) / 600) ** 2)) + 0.05;
      x += (Math.sin(2 * Math.PI * k * phase) * formant) / k;
    }
    const syllable = Math.min(1, Math.max(0, 0.5 + 0.9 * Math.sin(2 * Math.PI * 3.5 * t)));
    noise = (Math.imul(noise, 1664525) + 1013904223) >>> 0;
    const sibilant = t >= 1.2 && t < 1.35 ? 0.15 * ((noise / 4294967296) * 2 - 1) : 0;
    const gate = t < 1.85 ? 1 : 0;
    out[i] = gate * (0.25 * x * syllable + sibilant);
  }
  return out;
}

const VOICE = voice();
const CARRIER: [Float32Array, Float32Array] = (() => {
  const L = new Float32Array(FRAMES);
  const R = new Float32Array(FRAMES);
  for (let i = 0; i < FRAMES; i++) {
    L[i] = goldenInput(i, 0);
    R[i] = goldenInput(i, 1);
  }
  return [L, R];
})();
const sweeps = goldenSweeps(vocoderParams, SWEPT);

/** Renders `values` (a preset, or {} for the default patch) with the voice on the sidechain. */
function render(values: Record<string, ParamValue>): [Float32Array, Float32Array] {
  const params: Record<string, ParamValue | ((frame: number) => number)> = { ...values };
  for (const key of SWEPT) params[key] = sweeps[key] as (frame: number) => number;
  return runEffect(VocoderKernel, vocoderParams, (frame, channel) => (CARRIER[channel] as Float32Array)[frame] as number, FRAMES, {
    params,
    sidechain: (frame) => VOICE[frame] as number,
  });
}

function snapshot(values: Record<string, ParamValue>): Snapshot {
  const [L, R] = render(values);
  return {
    left: strided(L, 256).map((x) => Number(x.toFixed(7))),
    rmsL: chunkRms(L).map((x) => Number(x.toPrecision(6))),
    rmsR: chunkRms(R).map((x) => Number(x.toPrecision(6))),
  };
}

