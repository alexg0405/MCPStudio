/**
 * Golden output of the Tune kernel: the default patch and every preset, on a monophonic melody with
 * off-key notes (so the correction works), vibrato, a glide and a silent gap (so the unvoiced path
 * runs), with the speed and mix params swept by the CPU benchmark's automation in the whole run.
 *
 * The stored values are taken from the kernel before its pitch detector and drift were optimised:
 * every 256th left-channel sample, and the RMS of each 1024-frame chunk of both channels. The
 * tolerances are 0.002 on the samples and 0.1 dB on the chunk RMS. To regenerate, run
 * `TUNE_GOLDEN_RECORD=1 npx vitest run src/plugins/builtin/tune/golden.test.ts`: the test prints the
 * snapshots as one `GOLDEN_JSON` line, to paste between the GOLDEN markers.
 */
