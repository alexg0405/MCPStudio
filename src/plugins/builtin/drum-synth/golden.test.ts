interface Snapshot {
  /** Left channel every 256 frames. */
  left: number[];
  /** RMS of each 1024-frame chunk, per channel. */
  rmsL: number[];
  rmsR: number[];
}

const sweeps = goldenSweeps(drumSynthParams, SWEPT);

/** Renders `values` (a preset, or {} for the default patch) through the scripted pattern. */
function render(values: Record<string, ParamValue>): [Float32Array, Float32Array] {
  const k = new DrumSynthKernel(testHost(SR));
  k.transport = testTransport({ playing: true, bpm: 120, sampleRate: SR });
  let id = 1;
  const events = SCRIPT.map(([sec, key, vel]) => ({
    frame: Math.round(sec * SR),
    run: () => k.noteOn(key, vel, id++, 0, 0),
  }));
  const block = (b0: number) => {
    const v: Record<string, ParamValue> = { ...values };
    for (const key of SWEPT) v[key] = (sweeps[key] as (frame: number) => number)(b0);
    return paramBlock(drumSynthParams, v) as ParamBlock<typeof drumSynthParams>;
  };
  return renderInstrument(k, FRAMES, block, events);
}

function snapshot(values: Record<string, ParamValue>): Snapshot {
  const [L, R] = render(values);
  return {
    left: strided(L, 256).map((x) => Number(x.toFixed(7))),
    rmsL: chunkRms(L).map((x) => Number(x.toPrecision(6))),
    rmsR: chunkRms(R).map((x) => Number(x.toPrecision(6))),
  };
}

